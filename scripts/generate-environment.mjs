import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const envFile = resolve('.env.local');
const output = resolve('src/environments/environment.generated.ts');
const parsed = {};

if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (match) parsed[match[1]] = match[2].trim();
  }
}

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL ?? parsed.NEXT_PUBLIC_SUPABASE_URL ?? '';
const supabasePublishableKey = process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ?? parsed.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ?? '';
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, `// Generated by scripts/generate-environment.mjs\nexport const runtimeEnvironment = ${JSON.stringify({ supabaseUrl, supabasePublishableKey }, null, 2)} as const;\n`);
console.log(`Environment generated (${supabaseUrl ? 'Supabase configured' : 'demo mode'}).`);
